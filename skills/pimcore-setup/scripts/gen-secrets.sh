#!/usr/bin/env bash
# Generate credentials for a new Pimcore project without printing them.
# Writes <project>/.pimcore-setup/secrets.env (mode 600, folder 700) and, with
# --compose, <project>/docker-compose.override.yaml (mode 600). Adds git-ignore
# rules. Refuses to overwrite existing files. Prints paths and key names only.
# Usage: gen-secrets.sh <project-dir> [--compose] [--db-name N] [--db-user U]
#        [--dev-login] [--admin-user A] [--db-host H] [--db-port P] [--db-service S] [--php-services "php supervisord"]

set -eu
[ $# -ge 1 ] || { sed -n '2,7p' "$0"; exit 2; }
case "$1" in -h|--help) sed -n '2,7p' "$0"; exit 0 ;; esac
PROJECT="$1"; shift
DEVLOGIN=0; COMPOSE=0; DBNAME=""; DBUSER=""; ADMIN=""; DBHOST=""; DBPORT="3306"; DBSVC="db"; PHPSVCS="php supervisord"
while [ $# -gt 0 ]; do
  case "$1" in
    --compose) COMPOSE=1; shift ;;
    --dev-login) DEVLOGIN=1; shift ;;
    --db-name) DBNAME="$2"; shift 2 ;;
    --db-user) DBUSER="$2"; shift 2 ;;
    --admin-user) ADMIN="$2"; shift 2 ;;
    --db-host) DBHOST="$2"; shift 2 ;;
    --db-port) DBPORT="$2"; shift 2 ;;
    --db-service) DBSVC="$2"; shift 2 ;;
    --php-services) PHPSVCS="$2"; shift 2 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done
[ -d "$PROJECT" ] || { echo "project folder not found: $PROJECT" >&2; exit 1; }
cd "$PROJECT"

umask 077
DIR=".pimcore-setup"; SEC="$DIR/secrets.env"; OVR="docker-compose.override.yaml"
[ -e "$SEC" ] && { echo "refusing: $SEC exists (reuse it; regenerating can lock you out of an existing database)" >&2; exit 3; }
[ "$COMPOSE" = 1 ] && [ -e "$OVR" ] && { echo "refusing: $OVR exists" >&2; exit 3; }

rand() { # rand <length> : alphanumeric from a CSPRNG
  local n="$1" out=""
  while [ "${#out}" -lt "$n" ]; do
    if [ -r /dev/urandom ]; then out="$out$(LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom 2>/dev/null | head -c "$n")"
    elif command -v openssl >/dev/null 2>&1; then out="$out$(openssl rand -base64 48 | LC_ALL=C tr -dc 'A-Za-z0-9')"
    else echo "no secure random source (need /dev/urandom or openssl)" >&2; exit 4; fi
  done
  printf '%s' "${out:0:$n}"
}
slug=$(basename "$PWD" | tr 'A-Z' 'a-z' | tr -c 'a-z0-9\n' '_' | sed 's/__*/_/g; s/^_//; s/_$//' | cut -c1-32)
[ -n "$slug" ] || slug="pimcore"
DBNAME="${DBNAME:-$slug}"
DBUSER="${DBUSER:-$(printf '%s' "$slug" | cut -c1-24)_app}"
if [ "$DEVLOGIN" = 1 ]; then ADMIN="admin"; ADMINPASS="admin"; else ADMIN="${ADMIN:-admin_$(rand 6 | tr 'A-Z' 'a-z')}"; ADMINPASS="$(rand 28)"; fi
if [ -z "$DBHOST" ]; then if [ "$COMPOSE" = 1 ]; then DBHOST="$DBSVC"; else DBHOST="127.0.0.1"; fi; fi

mkdir -p "$DIR"; chmod 700 "$DIR"
{
  echo "# Generated by pimcore-toolkit gen-secrets.sh. Do not commit. Do not print."
  echo "PIMCORE_INSTALL_ADMIN_USERNAME=$ADMIN"
  echo "PIMCORE_INSTALL_ADMIN_PASSWORD=$ADMINPASS"
  echo "PIMCORE_INSTALL_MYSQL_HOST_SOCKET=$DBHOST"
  echo "PIMCORE_INSTALL_MYSQL_PORT=$DBPORT"
  echo "PIMCORE_INSTALL_MYSQL_DATABASE=$DBNAME"
  echo "PIMCORE_INSTALL_MYSQL_USERNAME=$DBUSER"
  echo "PIMCORE_INSTALL_MYSQL_PASSWORD=$(rand 28)"
  echo "DB_ROOT_PASSWORD=$(rand 32)"
} > "$SEC"
chmod 600 "$SEC"
[ "$DEVLOGIN" = 1 ] && echo "dev login: admin/admin (local development only; keep ports bound to 127.0.0.1)"
echo "created $SEC (600) keys: PIMCORE_INSTALL_ADMIN_USERNAME PIMCORE_INSTALL_ADMIN_PASSWORD PIMCORE_INSTALL_MYSQL_HOST_SOCKET PIMCORE_INSTALL_MYSQL_PORT PIMCORE_INSTALL_MYSQL_DATABASE PIMCORE_INSTALL_MYSQL_USERNAME PIMCORE_INSTALL_MYSQL_PASSWORD DB_ROOT_PASSWORD"

if [ "$COMPOSE" = 1 ]; then
  # Compose reads only .env for interpolation, so the override holds the values itself.
  getv() { grep "^$1=" "$SEC" | cut -d= -f2-; }
  UIDGID=""
  case "$(uname -s)" in Linux) UIDGID="$(id -u):$(id -g)" ;; esac
  {
    echo "# Generated by pimcore-toolkit gen-secrets.sh. Holds secrets: do not commit."
    echo "services:"
    echo "  $DBSVC:"
    echo "    environment:"
    echo "      MYSQL_ROOT_PASSWORD: \"$(getv DB_ROOT_PASSWORD)\""
    echo "      MYSQL_DATABASE: \"$DBNAME\""
    echo "      MYSQL_USER: \"$DBUSER\""
    echo "      MYSQL_PASSWORD: \"$(getv PIMCORE_INSTALL_MYSQL_PASSWORD)\""
    if [ -n "$UIDGID" ]; then
      for s in $PHPSVCS; do
        echo "  $s:"
        echo "    user: \"$UIDGID\""
      done
    fi
  } > "$OVR"
  chmod 600 "$OVR"
  echo "created $OVR (600) for services: $DBSVC${UIDGID:+ $PHPSVCS (user $UIDGID)}"
  echo "note: check that '$DBSVC' and the MYSQL_* variable names match the project's docker-compose.yaml"
fi

# git-ignore rules (normal permissions for .gitignore)
umask 022
touch .gitignore
added=0
for rule in "/.pimcore-setup/" "/config/local/" "/docker-compose.override.yaml" "/.env.local"; do
  grep -qxF "$rule" .gitignore || { printf '%s\n' "$rule" >> .gitignore; added=$((added+1)); }
done
echo "updated .gitignore (+$added rules)"
echo "read the admin login yourself with: grep ADMIN $DIR/secrets.env"
