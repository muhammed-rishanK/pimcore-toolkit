# Generate credentials for a new Pimcore project without printing them (Windows PowerShell 5.1 or 7).
# Same files and rules as gen-secrets.sh: .pimcore-setup\secrets.env and, with -Compose,
# docker-compose.override.yaml, both restricted to the current user; git-ignore rules added;
# existing files are never overwritten. Prints paths and key names only.
# Usage: powershell -ExecutionPolicy Bypass -File gen-secrets.ps1 -Project <dir> [-Compose]
#        [-DbName N] [-DbUser U] [-AdminUser A] [-DbHost H] [-DbPort 3306] [-DbService db]
param(
  [Parameter(Mandatory = $true)][string]$Project,
  [switch]$Compose,
  [string]$DbName = '', [string]$DbUser = '', [string]$AdminUser = '',
  [string]$DbHost = '', [int]$DbPort = 3306, [string]$DbService = 'db'
)
$ErrorActionPreference = 'Stop'
if (-not (Test-Path $Project -PathType Container)) { Write-Error "project folder not found: $Project"; exit 1 }
Set-Location $Project

$dir = '.pimcore-setup'; $sec = Join-Path $dir 'secrets.env'; $ovr = 'docker-compose.override.yaml'
if (Test-Path $sec) { Write-Error "refusing: $sec exists (reuse it; regenerating can lock you out of an existing database)"; exit 3 }
if ($Compose -and (Test-Path $ovr)) { Write-Error "refusing: $ovr exists"; exit 3 }

$alphabet = [char[]]'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789'
function New-Secret([int]$len) {
  $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
  $chars = New-Object char[] $len; $buf = New-Object byte[] 1; $i = 0
  while ($i -lt $len) {
    $rng.GetBytes($buf)
    if ($buf[0] -lt 248) { $chars[$i] = $alphabet[$buf[0] % 62]; $i++ }  # 248 = 4*62, no modulo bias
  }
  -join $chars
}
function Restrict($path) { # current user only
  $acl = Get-Acl $path
  $acl.SetAccessRuleProtection($true, $false)
  foreach ($r in @($acl.Access)) { [void]$acl.RemoveAccessRule($r) }
  $me = [System.Security.Principal.WindowsIdentity]::GetCurrent().Name
  $inherit = if ((Get-Item $path).PSIsContainer) { 'ContainerInherit,ObjectInherit' } else { 'None' }
  $acl.AddAccessRule((New-Object System.Security.AccessControl.FileSystemAccessRule($me, 'FullControl', $inherit, 'None', 'Allow')))
  Set-Acl $path $acl
}

$slug = ((Split-Path -Leaf (Get-Location)).ToLower() -replace '[^a-z0-9]+', '_').Trim('_')
if (-not $slug) { $slug = 'pimcore' }
if ($slug.Length -gt 32) { $slug = $slug.Substring(0, 32) }
if (-not $DbName) { $DbName = $slug }
if (-not $DbUser) { $DbUser = ($slug.Substring(0, [Math]::Min(24, $slug.Length))) + '_app' }
if (-not $AdminUser) { $AdminUser = 'admin_' + (New-Secret 6).ToLower() }
if (-not $DbHost) { $DbHost = if ($Compose) { $DbService } else { '127.0.0.1' } }

New-Item -ItemType Directory -Force $dir | Out-Null; Restrict $dir
$dbPass = New-Secret 28; $rootPass = New-Secret 32
$lines = @(
  '# Generated by pimcore-toolkit gen-secrets.ps1. Do not commit. Do not print.'
  "PIMCORE_INSTALL_ADMIN_USERNAME=$AdminUser"
  "PIMCORE_INSTALL_ADMIN_PASSWORD=$(New-Secret 28)"
  "PIMCORE_INSTALL_MYSQL_HOST_SOCKET=$DbHost"
  "PIMCORE_INSTALL_MYSQL_PORT=$DbPort"
  "PIMCORE_INSTALL_MYSQL_DATABASE=$DbName"
  "PIMCORE_INSTALL_MYSQL_USERNAME=$DbUser"
  "PIMCORE_INSTALL_MYSQL_PASSWORD=$dbPass"
  "DB_ROOT_PASSWORD=$rootPass"
)
# LF line endings so the file can be sourced by sh inside containers
[System.IO.File]::WriteAllText((Join-Path (Get-Location) $sec), (($lines -join "`n") + "`n"))
Restrict $sec
Write-Output "created $sec (current user only) keys: PIMCORE_INSTALL_ADMIN_USERNAME PIMCORE_INSTALL_ADMIN_PASSWORD PIMCORE_INSTALL_MYSQL_HOST_SOCKET PIMCORE_INSTALL_MYSQL_PORT PIMCORE_INSTALL_MYSQL_DATABASE PIMCORE_INSTALL_MYSQL_USERNAME PIMCORE_INSTALL_MYSQL_PASSWORD DB_ROOT_PASSWORD"

if ($Compose) {
  $y = @(
    '# Generated by pimcore-toolkit gen-secrets.ps1. Holds secrets: do not commit.'
    'services:'
    "  ${DbService}:"
    '    environment:'
    "      MYSQL_ROOT_PASSWORD: `"$rootPass`""
    "      MYSQL_DATABASE: `"$DbName`""
    "      MYSQL_USER: `"$DbUser`""
    "      MYSQL_PASSWORD: `"$dbPass`""
  )
  [System.IO.File]::WriteAllText((Join-Path (Get-Location) $ovr), (($y -join "`n") + "`n"))
  Restrict $ovr
  Write-Output "created $ovr (current user only) for service: $DbService"
  Write-Output "note: check that '$DbService' and the MYSQL_* variable names match the project's docker-compose.yaml"
}
$dbPass = $null; $rootPass = $null

if (-not (Test-Path .gitignore)) { New-Item -ItemType File .gitignore | Out-Null }
$existing = Get-Content .gitignore -ErrorAction SilentlyContinue
$added = 0
foreach ($rule in '/.pimcore-setup/', '/config/local/', '/docker-compose.override.yaml', '/.env.local') {
  if ($existing -notcontains $rule) { Add-Content .gitignore $rule; $added++ }
}
Write-Output "updated .gitignore (+$added rules)"
Write-Output "read the admin login yourself with: Select-String ADMIN $sec"
